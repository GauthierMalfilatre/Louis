#!/usr/bin/env bash
##
## EPITECH PROJECT, 2026
## SENSAI
## File description:
## Install the louis command, to run the assistant in the current directory
##
## Usage: ./install.sh              install (or update) louis
##        ./install.sh --uninstall  remove it
##
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOUIS_HOME="${LOUIS_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/louis}"
BIN_DIR="${LOUIS_BIN_DIR:-$HOME/.local/bin}"
VENV="$LOUIS_HOME/venv"
DATABASE="$LOUIS_HOME/louis.db"
TRACES="$LOUIS_HOME/louis.traces.jsonl"
KNOWLEDGE="$LOUIS_HOME/louis.rag.db"
LAUNCHER="$BIN_DIR/louis"

info() { printf '\033[1;34m::\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

if [[ "${1:-}" == "--uninstall" ]]; then
    rm -f "$LAUNCHER"
    rm -rf "$VENV"
    # The sessions are the user's history: never deleted without asking
    rmdir "$LOUIS_HOME" 2>/dev/null || true
    info "louis has been uninstalled."
    [[ -f "$DATABASE" ]] && info "Your sessions are kept in $DATABASE: delete it yourself if you don't need them."
    [[ -f "$TRACES" ]] && info "The metrics of your calls are kept in $TRACES: delete it yourself if you don't need them."
    [[ -f "$KNOWLEDGE" ]] && info "Your knowledge base is kept in $KNOWLEDGE: delete it yourself if you don't need it."
    exit 0
elif [[ $# -gt 0 ]]; then
    die "Unknown option '$1'. Usage: $0 [--uninstall]"
fi

# src/ nests the same quotes inside f-strings, which needs Python 3.12 (PEP 701)
PYTHON=""
for candidate in python3.14 python3.13 python3.12 python3; do
    if command -v "$candidate" >/dev/null \
        && "$candidate" -c 'import sys; sys.exit(sys.version_info < (3, 12))' 2>/dev/null; then
        PYTHON="$(command -v "$candidate")"
        break
    fi
done
[[ -n "$PYTHON" ]] || die "Python 3.12 or newer is required."
info "Using $("$PYTHON" --version) ($PYTHON)"

info "Creating the virtual environment in $VENV"
mkdir -p "$LOUIS_HOME"
"$PYTHON" -m venv --clear "$VENV" \
    || die "Cannot create the virtual environment. On Debian/Ubuntu: sudo apt install python3-venv"

info "Installing the dependencies"
"$VENV/bin/pip" install --quiet --disable-pip-version-check -r "$REPO/requirements.txt"

# Heavier, and only if the settings of this checkout ask for it: venv --clear above wiped any earlier install of it,
# so this must run on every install.sh, not only the first one, or guard.enabled silently stops working after a pull
GUARD="$("$VENV/bin/python" -c 'import sys; sys.path.insert(0, sys.argv[1]); from config.settings import settings as s; print(s.get("guard.enabled", False))' "$REPO/src")"
if [[ "$GUARD" == "True" ]]; then
    info "guard.enabled is on: installing NeMo Guardrails (requirements-guard.txt)"
    if "$VENV/bin/pip" install --quiet --disable-pip-version-check -r "$REPO/requirements-guard.txt" \
        && "$VENV/bin/python" -m spacy download en_core_web_lg --quiet; then
        info "NeMo Guardrails installed"
    else
        warn "Could not install the guardrails (NeMo needs Python 3.10 to 3.13; this venv uses $("$VENV/bin/python" --version)): retry with"
        warn "  $VENV/bin/pip install -r $REPO/requirements-guard.txt && $VENV/bin/python -m spacy download en_core_web_lg"
    fi
fi

# The same for the reranker of the knowledge base, and its model downloaded now: louis never downloads it during a chat.
# The model is kept out of the venv (~/.cache/louis/rerank), venv --clear does not download it again
RERANK="$("$VENV/bin/python" -c 'import sys; sys.path.insert(0, sys.argv[1]); from config.settings import settings as s; print(bool(s.get("rag.enabled") and s.get("rag.rerank.enabled")))' "$REPO/src")"
if [[ "$RERANK" == "True" ]]; then
    info "rag.rerank.enabled is on: installing fastembed (requirements-rerank.txt) and the reranking model"
    if "$VENV/bin/pip" install --quiet --disable-pip-version-check -r "$REPO/requirements-rerank.txt" \
        && (cd "$REPO/src" && "$VENV/bin/python" -m rag.reranker >/dev/null); then
        info "Reranker installed"
    else
        warn "Could not install the reranker: the knowledge base is searched without it. Retry with"
        warn "  $VENV/bin/pip install -r $REPO/requirements-rerank.txt && (cd $REPO/src && $VENV/bin/python -m rag.reranker)"
    fi
fi

# The launcher runs the sources of this repository: a git pull updates louis,
# and louis keeps the directory it was typed in as the project it works on.
# It saves the sessions in the global database, and the traces of its calls next to it (louis --dashboard reads them
# all, whatever the project), and keeps the knowledge base there too (documentation is not about one project):
# run from the repository, louis uses the ones in the working directory
info "Installing the launcher in $LAUNCHER"
mkdir -p "$BIN_DIR"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by $REPO/install.sh
export LOUIS_DB=$(printf '%q' "$DATABASE")
export LOUIS_TRACES=$(printf '%q' "$TRACES")
export LOUIS_RAG=$(printf '%q' "$KNOWLEDGE")
exec $(printf '%q' "$VENV/bin/python") $(printf '%q' "$REPO/src/main.py") "\$@"
EOF
chmod +x "$LAUNCHER"

case ":$PATH:" in
    *":$BIN_DIR:"*)
        if [[ "$(command -v louis)" != "$LAUNCHER" ]]; then
            warn "Another louis comes first in your PATH: $(command -v louis)"
        fi
        ;;
    *)
        warn "$BIN_DIR is not in your PATH. Add this line to your ~/.bashrc or ~/.zshrc:"
        printf '    export PATH="%s:$PATH"\n' "$BIN_DIR" >&2
        ;;
esac

MODEL="$("$VENV/bin/python" -c 'import sys; sys.path.insert(0, sys.argv[1]); from config.settings import settings as s; print(s["chat.model.name"] + ":" + s["chat.model.parameters"])' "$REPO/src")"
if ! command -v ollama >/dev/null; then
    warn "Ollama is not installed, louis needs it to run $MODEL: https://ollama.com/download"
elif ! models="$(ollama list 2>/dev/null)"; then
    warn "Ollama is not running, start it before using louis: ollama serve"
elif ! awk -v model="$MODEL" 'NR > 1 && $1 == model { found = 1 } END { exit !found }' <<<"$models"; then
    warn "The model $MODEL is not downloaded yet: ollama pull $MODEL"
fi

# Optional: without it, the knowledge base (/index) is searched by keywords only
EMBED="$("$VENV/bin/python" -c 'import sys; sys.path.insert(0, sys.argv[1]); from config.settings import settings as s; print(s["rag.embed.model"])' "$REPO/src")"
if [[ -n "${models:-}" ]] \
    && ! awk -v model="$EMBED" 'NR > 1 && ($1 == model || $1 == model ":latest") { found = 1 } END { exit !found }' <<<"$models"; then
    warn "The embedding model $EMBED is not downloaded yet (for the knowledge base): ollama pull $EMBED"
fi

# Optional too: the model that describes the code of the sources indexed with --describe (empty: the chat model)
DESCRIBE="$("$VENV/bin/python" -c 'import sys; sys.path.insert(0, sys.argv[1]); from config.settings import settings as s; print(s.get("rag.describe.model") or "")' "$REPO/src")"
if [[ -n "${models:-}" && -n "$DESCRIBE" ]] \
    && ! awk -v model="$DESCRIBE" 'NR > 1 && ($1 == model || $1 == model ":latest") { found = 1 } END { exit !found }' <<<"$models"; then
    warn "The model $DESCRIBE is not downloaded yet (it describes the code for /index --describe): ollama pull $DESCRIBE"
fi

info "Done! Type 'louis' in any directory to start it there."
info "louis runs from $REPO: keep this folder, and run install.sh again when requirements.txt changes."
