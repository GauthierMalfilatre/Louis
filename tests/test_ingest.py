import os
import shutil
import subprocess
import sys
import tempfile
import unittest
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
from rag.ingest import generated, skipped, scan, last_changes, modified_at

class GeneratedTest(unittest.TestCase):
    def test_marked_in_its_first_lines(self):
        self.assertIn("@generated", generated("// @generated by protoc\nint x;\n"))
        self.assertIn("do not edit", generated("# Code generated. DO NOT EDIT.\nx = 1\n"))

    def test_a_mark_further_down_does_not_count(self):
        self.assertIsNone(generated("a\nb\nc\nd\ne\nf\n# do not edit this section by hand\n"))

    def test_long_and_repetitive(self):
        grid = "\n".join(["config-v%d:" % (i % 3), "  lr: 0.001", "  batch: 64"][i % 3] for i in range(900))
        self.assertIn("lignes distinctes", generated(grid))

    def test_written_by_hand(self):
        code = "\n".join(f"def function_{i}(x):\n    return x * {i}\n" for i in range(300))
        self.assertIsNone(generated(code))

    def test_short_files_are_never_repetitive_enough(self):
        self.assertIsNone(generated("x = 1\n" * 100))

    def test_ratio_zero_reads_only_the_marks(self):
        self.assertIsNone(generated("x = 1\n" * 1000, ratio=0))
        self.assertIsNotNone(generated("# @generated\n" + "x = 1\n" * 1000, ratio=0))

class SkippedTest(unittest.TestCase):
    def test_left_out_by_their_name(self):
        for name in ("package-lock.json", ".env", ".env.local", "server.pem", "id_rsa", "app.min.js", "louis.rag.db"):
            self.assertTrue(skipped(name), name)
        for name in ("app.py", "README.md", "settings.yml"):
            self.assertFalse(skipped(name), name)

    def test_scan_leaves_out_dependencies(self):
        with tempfile.TemporaryDirectory() as root:
            for path in ("src/app.py", "node_modules/lib/index.js", ".git/config", ".env"):
                os.makedirs(os.path.dirname(os.path.join(root, path)) or root, exist_ok=True)
                with open(os.path.join(root, path), "w") as file:
                    file.write("x")
            self.assertEqual([os.path.relpath(p, root) for p in scan(root)], [os.path.join("src", "app.py")])

@unittest.skipIf(shutil.which("git") is None, "git is not installed")
class HistoryTest(unittest.TestCase):
    def git(self, *args, date=None):
        env = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
               "GIT_COMMITTER_EMAIL": "t@t"}
        if date:
            env["GIT_AUTHOR_DATE"] = env["GIT_COMMITTER_DATE"] = date
        subprocess.run(["git", "-C", self.root, *args], check=True, capture_output=True, env=env)

    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.root = self.folder.name
        os.makedirs(os.path.join(self.root, "pkg"))
        self.git("init", "-q")
        for name in ("pkg/a.py", "pkg/b.py"):
            self.write(name, "v1")
        self.git("add", ".")
        self.git("commit", "-q", "-m", "first", date="2026-01-01T12:00:00")
        self.write("pkg/b.py", "v2")
        self.git("commit", "-q", "-am", "second", date="2026-03-01T12:00:00")

    def write(self, name, text):
        with open(os.path.join(self.root, name), "w") as file:
            file.write(text)

    def tearDown(self):
        self.folder.cleanup()

    def test_the_last_commit_of_each_file(self):
        dates = last_changes(self.root)
        self.assertLess(dates["/pkg/a.py"], dates["/pkg/b.py"])
        self.assertAlmostEqual(dates["/pkg/b.py"] - dates["/pkg/a.py"], 59 * 86400, delta=3600)

    def test_paths_from_a_folder_below_the_root(self):
        self.assertEqual(set(last_changes(os.path.join(self.root, "pkg"))), {"/a.py", "/b.py"})

    def test_a_file_git_does_not_follow_takes_its_date_on_the_disk(self):
        path = os.path.join(self.root, "pkg/new.py")
        self.write("pkg/new.py", "new")
        self.assertEqual(modified_at(path, "/pkg/new.py", last_changes(self.root)), os.path.getmtime(path))

    def test_not_a_repository(self):
        with tempfile.TemporaryDirectory() as root:
            self.assertEqual(last_changes(root), {})

if __name__ == "__main__":
    unittest.main()
